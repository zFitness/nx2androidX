/**
 * The tar reader, on the archives the app unpacks: the rootfs (GNU format, long names, links) and a pax archive
 * whose file size is only in the pax header.
 */
class TarTest {

    @Test
    fun gnuArchive() {
        val dir = Files.createTempDirectory("nx2a-tar").toFile()
        val tar = Base64.getDecoder().decode(GNU)
        Tar.unpack(tar.inputStream(), dir)

        assertEquals("hello world\n", File(dir, "dir/small.txt").readText())
        assertEquals(1000L, File(dir, "dir/thousand.bin").length())
        assertEquals("abc", File(dir, "dir/deep/deep/deep/deep/deep/deep/deep/deep/deep/deep/deep/deep/name.txt").readText())
        assertTrue("the symbolic link", Files.isSymbolicLink(File(dir, "dir/link").toPath()))
        assertEquals("small.txt", Files.readSymbolicLink(File(dir, "dir/link").toPath()).toString())
        assertEquals("hello world\n", File(dir, "dir/hard").readText())
        assertTrue("the program's permission bits", File(dir, "dir/program").canExecute())
        assertTrue("a plain file is not executable", !File(dir, "dir/small.txt").canExecute())
    }

    @Test
    fun paxArchive() {
        val dir = Files.createTempDirectory("nx2a-tar").toFile()
        val tar = Base64.getDecoder().decode(PAX)
        Tar.unpack(tar.inputStream(), dir)
        // the long path is in a pax header, not in the ustar header
        assertEquals("paxxy", File(dir, "pax/deep/deep/deep/deep/deep/deep/deep/deep/deep/deep/deep/deep/deep/deep/file.txt").readText())
        assertEquals("abc", File(dir, "pax/small.txt").readText())
    }

    /**
     * The environment's archive: the entries live under a few roots, and the first segment of a path says which
     * root it belongs to.
     */
    @Test
    fun anArchiveWithRoots() {
        val dir = Files.createTempDirectory("nx2a-tar").toFile()
        val rootfs = File(dir, "rootfs")
        val tool = File(dir, "tool")
        val tar = archive(
            "rootfs/usr/bin/python3.13" to "#!/bin/sh\n",
            "tool/porter/cli.py" to "print('hi')\n",
            "tool/toolchain/clang" to "a compiler",
            "elsewhere/ignored" to "not ours\n",
        )
        var written = 0L
        Tar.unpack(tar.inputStream(), mapOf("rootfs" to rootfs, "tool" to tool)) { written = it }

        assertEquals("#!/bin/sh\n", File(rootfs, "usr/bin/python3.13").readText())
        assertEquals("print('hi')\n", File(tool, "porter/cli.py").readText())
        assertEquals("a compiler", File(tool, "toolchain/clang").readText())
        assertFalse("an entry under another root is skipped", File(dir, "elsewhere/ignored").exists())
        assertTrue("the progress is told", written > 0)
    }

    /**
     * The writer, read back by the reader: the round trip the export's data takes. The bytes it reports are
     * the bytes of the files (what the progress shows).
     */
    @Test
    fun aWrittenArchiveReadsBack() {
        val src = Files.createTempDirectory("nx2a-tar-src").toFile()
        val sub = File(src, "mods")
        sub.mkdirs()
        File(sub, "main.bin").writeBytes(ByteArray(100_000) { (it % 251).toByte() })
        File(src, "env.txt").writeText("DM_LANG=zh-Hans\n")
        val out = java.io.ByteArrayOutputStream()
        var gone = 0L
        TarWriter(out).use { w ->
            w.putDirectory("mods")
            w.putFile("mods/main.bin", File(src, "mods/main.bin")) { gone += it }
            w.putBytes("env.txt", "DM_LANG=zh-Hans\n".toByteArray())
        }

        val dir = Files.createTempDirectory("nx2a-tar-back").toFile()
        Tar.unpack(out.toByteArray().inputStream(), dir)
        assertTrue("the file's bytes are the bytes it reported", gone == 100_000L)
        assertEquals(100_000, File(dir, "mods/main.bin").length())
        assertTrue(File(dir, "mods/main.bin").readBytes().contentEquals(File(src, "mods/main.bin").readBytes()))
        assertEquals("DM_LANG=zh-Hans\n", File(dir, "env.txt").readText())
    }

    /** A name that does not fit the header goes out as a GNU long-name entry, and the reader gets it back */
    @Test
    fun aLongNameSurvivesTheRoundTrip() {
        val deep = "RomFS/" + "deep/".repeat(30) + "a-file-with-a-name-longer-than-the-header-holds.bin"
        val out = java.io.ByteArrayOutputStream()
        TarWriter(out).use { w -> w.putBytes(deep, "deep content".toByteArray()) }

        val dir = Files.createTempDirectory("nx2a-tar-long").toFile()
        Tar.unpack(out.toByteArray().inputStream(), dir)
        assertEquals("deep content", File(dir, deep).readText())
    }

    /**
     * The assistant's engine travels in the same archive: it lands in the assistant's own folder, in the
     * engine's own folder inside it.
     */
    @Test
    fun anArchiveWithTheEngine() {
        val dir = Files.createTempDirectory("nx2a-tar").toFile()
        val rootfs = File(dir, "rootfs")
        val tool = File(dir, "tool")
        val agent = File(dir, "agent")
        val tar = archive(
            "rootfs/usr/bin/python3.13" to "#!/bin/sh\n",
            "agent/runtime/pi" to "the engine\n",
            "agent/runtime/manifest.json" to "{}\n",
        )
        Tar.unpack(tar.inputStream(), mapOf("rootfs" to rootfs, "tool" to tool, "agent" to agent))

        assertEquals("the engine\n", File(agent, "runtime/pi").readText())
        assertEquals("{}\n", File(agent, "runtime/manifest.json").readText())
        assertFalse("the assistant's data is not the environment's", File(agent, "models.json").exists())
    }

    /** A small ustar archive: the files it holds, in the order they are given */
    private fun archive(vararg entries: Pair<String, String>): ByteArray {
        val out = java.io.ByteArrayOutputStream()
        for ((name, content) in entries) {
            val data = content.toByteArray()
            val header = ByteArray(512)
            name.toByteArray().copyInto(header, 0, 0, minOf(name.length, 100))
            "0000644\u0000".toByteArray().copyInto(header, 100)
            "0000000\u0000".toByteArray().copyInto(header, 108)
            "0000000\u0000".toByteArray().copyInto(header, 116)
            ("%011o\u0000".format(data.size)).toByteArray().copyInto(header, 124)
            "00000000000\u0000".toByteArray().copyInto(header, 136)
            header[156] = '0'.code.toByte()
            for (i in 148 until 156) header[i] = ' '.code.toByte()
            var sum = 0
            for (b in header) sum += b.toInt() and 0xff
            ("%06o\u0000 ".format(sum)).toByteArray().copyInto(header, 148)
            out.write(header)
            out.write(data)
            val pad = (512 - data.size % 512) % 512
            if (pad > 0) out.write(ByteArray(pad))
        }
        out.write(ByteArray(1024))   // the end of the archive
        return out.toByteArray()
    }

